"""Build the Docsify navigation for guides/: the home page and one sidebar per guide locale.

Reads the folder structure and each guide's <locale>/README.md progress table, so new
guides show up without manual edits. Generated files: guides/README.md,
guides/_sidebar.md and guides/<kind>/<slug>/<locale>/_sidebar.md.
"""
import re
from pathlib import Path

GUIDES = Path(__file__).resolve().parent.parent / "guides"
LOCALES = ("en", "es", "pt")
FLAGS = {"en": "🇺🇸 EN", "es": "🇪🇸 ES", "pt": "🇧🇷 PT"}
KINDS = {
    "languages": {"en": "Languages", "es": "Lenguajes", "pt": "Linguagens"},
    "frameworks": {"en": "Frameworks", "es": "Frameworks", "pt": "Frameworks"},
}
HOME = {"en": "Home", "es": "Inicio", "pt": "Início"}
INDEX = {"en": "Index and progress", "es": "Índice y progreso", "pt": "Índice e progresso"}
TASKFLOW = "TaskFlow"
GENERATED = "<!-- Generated by scripts/build_nav.py: do not edit by hand. -->\n\n"


def title_of(md: Path) -> str:
    for line in md.read_text().splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return md.parent.name


def chapters(readme: Path):
    """Rows of the progress table: | NN | [Name](file.md) | ..."""
    for m in re.finditer(r"^\|\s*(\d{2})\s*\|\s*\[(.+?)\]\((.+?\.md)\)", readme.read_text(), re.M):
        yield m.group(1), m.group(2), m.group(3)


def guides():
    for kind in KINDS:
        base = GUIDES / kind
        if not base.is_dir():
            continue
        for g in sorted(p for p in base.iterdir() if p.is_dir()):
            locales = [l for l in LOCALES if (g / l / "README.md").exists()]
            if locales:
                yield kind, g, locales


def write_sidebar(kind, guide: Path, loc: str):
    folder = guide / loc
    lines = [f"- [🏠 {HOME[loc]}](/README.md)", "",
             f"- **{title_of(guide / 'README.md')}**",
             f"  - [{INDEX[loc]}](README.md)"]
    if (folder / "taskflow.md").exists():
        lines.append(f"  - [{TASKFLOW}](taskflow.md)")
    for num, name, href in chapters(folder / "README.md"):
        lines.append(f"  - [{num} · {name}]({href})")
    others = " · ".join(f"[{FLAGS[l]}](../{l}/README.md)" for l in LOCALES if l != loc
                        and (guide / l / "README.md").exists())
    if others:
        lines += ["", f"- 🌐 {others}"]
    (folder / "_sidebar.md").write_text(GENERATED + "\n".join(lines) + "\n")


def write_home(found):
    by_kind = {k: [(g, locs) for kk, g, locs in found if kk == k] for k in KINDS}
    out = [GENERATED, "# Study Guides · Guías de estudio · Guias de estudo\n"]
    side = []
    for kind, labels in KINDS.items():
        heading = " · ".join(dict.fromkeys(labels.values()))
        out.append(f"## {heading}\n")
        side.append(f"- **{heading}**")
        rows = by_kind[kind]
        if not rows:
            out.append("—\n")
            continue
        out.append("| Guide | " + " | ".join(FLAGS[l] for l in LOCALES) + " |")
        out.append("|---|" + "---|" * len(LOCALES))
        for g, locs in rows:
            name = title_of(g / "README.md")
            rel = "/" + g.relative_to(GUIDES).as_posix()  # absolute: this sidebar also shows in subfolders
            cells = [f"[{FLAGS[l]}]({rel}/{l}/README.md)" if l in locs else "—" for l in LOCALES]
            out.append(f"| **{name}** | " + " | ".join(cells) + " |")
            first = "pt" if "pt" in locs else locs[0]
            side.append(f"  - [{name}]({rel}/{first}/README.md)")
        out.append("")
    (GUIDES / "README.md").write_text("\n".join(out))
    (GUIDES / "_sidebar.md").write_text(GENERATED + "\n".join(side) + "\n")


def main():
    found = list(guides())
    for kind, g, locs in found:
        for loc in locs:
            write_sidebar(kind, g, loc)
    write_home(found)
    print(f"navigation built for {len(found)} guide(s)")


if __name__ == "__main__":
    main()
